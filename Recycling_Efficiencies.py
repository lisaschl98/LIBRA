def _sum_abs(comp_abs: dict) -> float:
    return float(sum(float(v) for v in (comp_abs or {}).values()))


# Stoichiometric products — do not scale down when normalizing comp_abs to stream mass.
_COMP_ABS_NORMALIZE_PRESERVE_KEYS: frozenset[str] = frozenset({
    "process:Na2SO4",
    "process:Li2CO3",
    "process:Na2CO3",
    "process:NixCoyMnz(OH)2",
})


def _is_preserved_normalize_key(key: str) -> bool:
    """Inventory and stoich tags kept when comp_abs sum exceeds stream mass."""
    ks = str(key)
    if ks in _COMP_ABS_NORMALIZE_PRESERVE_KEYS:
        return True
    if ks.startswith("cell:"):
        return True
    return False


def _get_comp_abs_from_flow(flow_in, m_in: float, tol: float = 1e-9) -> dict:
    """
    Return absolute kg/h composition dict from flow meta; fallback from fractions.
    Robust:
      - if sum(comp_abs) < m_in: add remainder as __untracked__
      - if sum(comp_abs) > m_in: scale non-preserved components to match m_in
        (preserves e.g. ``process:Na2SO4`` from stoichiometry)
    """
    meta = getattr(flow_in, "meta", {}) or {}

    def _normalize_to_m_in(comp_abs: dict) -> dict:
        comp_abs = {str(k): float(v) for k, v in (comp_abs or {}).items()}
        s = sum(comp_abs.values())

        if m_in <= tol:
            return {}

        # too large -> scale down non-preserved keys only
        if s > m_in + tol and s > 0:
            preserved = {k: v for k, v in comp_abs.items() if _is_preserved_normalize_key(k)}
            m_preserved = float(sum(preserved.values()))
            rest = {k: v for k, v in comp_abs.items() if k not in preserved}
            m_rest = float(sum(rest.values()))
            m_rest_target = max(0.0, m_in - m_preserved)
            if m_rest > tol and m_rest_target > tol:
                f = m_rest_target / m_rest
                rest = {k: v * f for k, v in rest.items()}
            elif m_rest_target <= tol:
                rest = {}
            comp_abs = dict(rest)
            comp_abs.update(preserved)
            return comp_abs

        # too small -> add remainder
        if s < m_in - tol:
            comp_abs["__untracked__"] = comp_abs.get("__untracked__", 0.0) + (m_in - s)

        return comp_abs

    # 1) comp_abs available
    comp_abs = meta.get("comp_abs") or {}
    if isinstance(comp_abs, dict) and comp_abs:
        return _normalize_to_m_in(comp_abs)

    # 2) fallback from fractions
    comp_frac = meta.get("comp") or {}
    if isinstance(comp_frac, dict) and comp_frac:
        comp_abs = {str(k): float(v) * float(m_in) for k, v in comp_frac.items()}
        return _normalize_to_m_in(comp_abs)

    # 3) nothing available -> everything untracked
    return {"__untracked__": float(m_in)}



def _resolve_comp_key(comp_abs_in: dict, comp_key: str) -> str:
    """Match partition keys to comp_abs keys (case-insensitive for process:* tags)."""
    comp_key = str(comp_key)
    if comp_key in comp_abs_in:
        return comp_key
    ck = comp_key.lower()
    for k in comp_abs_in:
        if str(k).lower() == ck:
            return str(k)
    return comp_key


def _collapse_partition(partition: dict, comp_abs_in: dict) -> dict[str, dict]:
    """Merge partition rules that resolve to the same comp_abs key (e.g. H2O_NMC_wash vs H2O_nmc_wash)."""
    collapsed: dict[str, dict] = {}
    for comp_key, dests in (partition or {}).items():
        rk = _resolve_comp_key(comp_abs_in, str(comp_key))
        bucket = collapsed.setdefault(rk, {})
        for stream, frac in (dests or {}).items():
            stream = str(stream)
            bucket[stream] = max(float(bucket.get(stream, 0.0)), float(frac))
    return collapsed


def partition_comp_abs(
    comp_abs_in: dict,
    partition: dict,
    default_stream: str = "out",
) -> dict[str, dict]:
    """
    partition:
      { "<comp_key>": { "<stream>": fraction, ... }, ... }
    Returns:
      streams_comp_abs: {stream: {comp_key: kg/h, ...}, ...}

    Unmapped remainder of each comp_key stays in default_stream.
    Components not mentioned in partition go fully to default_stream.
    """
    comp_abs_in = {str(k): float(v) for k, v in (comp_abs_in or {}).items()}

    streams: dict[str, dict] = {}
    streams.setdefault(default_stream, {})

    # start: everything goes to default
    for k, v in comp_abs_in.items():
        if abs(v) > 1e-12:
            streams[default_stream][k] = streams[default_stream].get(k, 0.0) + v

    # reroute for partitioned keys (dedupe aliases that map to the same component)
    for comp_key, dests in _collapse_partition(partition, comp_abs_in).items():
        m = float(comp_abs_in.get(comp_key, 0.0))
        if abs(m) <= 1e-12:
            continue

        # remove full component from default first
        if comp_key in streams[default_stream]:
            streams[default_stream][comp_key] -= m
            if abs(streams[default_stream][comp_key]) < 1e-12:
                streams[default_stream].pop(comp_key, None)

        allocated = 0.0
        for stream, frac in (dests or {}).items():
            stream = str(stream)
            f = float(frac)
            if f <= 0:
                continue
            streams.setdefault(stream, {})
            add = m * f
            allocated += add
            streams[stream][comp_key] = streams[stream].get(comp_key, 0.0) + add

        # remainder goes back to default if fractions don't sum to 1
        rem = m - allocated
        if abs(rem) > 1e-12:
            streams[default_stream][comp_key] = streams[default_stream].get(comp_key, 0.0) + rem

    # clean zeros
    cleaned: dict[str, dict] = {}
    for s, d in streams.items():
        dd = {k: v for k, v in (d or {}).items() if abs(float(v)) > 1e-12}
        if dd:
            cleaned[s] = dd
    return cleaned


def apply_yields(
    streams_comp_abs: dict[str, dict],
    yields: dict[str, float],
    loss_sink: str = "loss",
) -> dict[str, dict]:
    """
    yields: { "<stream>": yield_factor }  (0..1)
    For each stream with yield<1: moves (1-y) of ALL components in that stream into loss_sink.
    """
    out = {s: dict(d) for s, d in (streams_comp_abs or {}).items()}
    loss_sink = str(loss_sink)

    for stream, y in (yields or {}).items():
        stream = str(stream)
        if stream not in out:
            continue

        y = float(y)
        y = max(0.0, min(1.0, y))
        if abs(y - 1.0) < 1e-12:
            continue

        d = out.get(stream, {})
        if not d:
            continue

        out.setdefault(loss_sink, {})
        loss_d = out[loss_sink]

        for k, v in list(d.items()):
            v = float(v)
            kept = v * y
            lost = v - kept

            if abs(kept) > 1e-12:
                d[k] = kept
            else:
                d.pop(k, None)

            if abs(lost) > 1e-12:
                loss_d[k] = loss_d.get(k, 0.0) + lost

    # cleanup
    cleaned: dict[str, dict] = {}
    for s, d in out.items():
        dd = {k: v for k, v in (d or {}).items() if abs(float(v)) > 1e-12}
        if dd:
            cleaned[s] = dd
    return cleaned


def build_outputs_from_comp_abs(streams_comp_abs: dict[str, dict], meta_in: dict | None = None):
    """
    Creates outputs dict[str, MassFlow] with:
      mass_kg_per_h = sum(comp_abs)
      meta: comp_abs + comp(fractions)
    """
    from Massflow import MassFlow  # local import to avoid circulars

    meta_in = dict(meta_in or {})
    outputs: StreamOutputs = StreamOutputs()

    for stream, comp_abs in (streams_comp_abs or {}).items():
        m = _sum_abs(comp_abs)
        comp = {k: float(v) / m for k, v in comp_abs.items()} if m > 0 else {}
        outputs[stream] = MassFlow(
            m,
            meta={**meta_in, "comp_abs": comp_abs, "comp": comp},
        )

    return outputs


def apply_component_yields(
    streams_comp_abs: dict[str, dict],
    yield_component: dict[str, float],
    loss_sink: str = "loss",
) -> dict[str, dict]:
    """
    yield_component: { "<comp_key>": yield_factor }.

    Moves (1-y) of that component into loss_sink, wherever the component sits.
    Other components in the same stream stay at their full mass.
    """
    out = {s: dict(d) for s, d in (streams_comp_abs or {}).items()}
    loss_sink = str(loss_sink)
    if not yield_component:
        return out

    for comp_key, y in yield_component.items():
        y = max(0.0, min(1.0, float(y)))
        if abs(y - 1.0) < 1e-12:
            continue
        for stream, d in list(out.items()):
            if stream == loss_sink:
                continue
            actual = _resolve_comp_key(d, str(comp_key))
            if actual not in d:
                continue
            v = float(d[actual])
            kept = v * y
            lost = v - kept
            if abs(kept) > 1e-12:
                d[actual] = kept
            else:
                d.pop(actual, None)
            if abs(lost) > 1e-12:
                out.setdefault(loss_sink, {})
                out[loss_sink][actual] = float(out[loss_sink].get(actual, 0.0)) + lost

    cleaned: dict[str, dict] = {}
    for s, d in out.items():
        dd = {k: v for k, v in (d or {}).items() if abs(float(v)) > 1e-12}
        if dd:
            cleaned[s] = dd
    return cleaned


def apply_partition_and_yield(
    step: str,
    flow_in,
    default_stream: str,
    partition: dict | None = None,
    yields: dict | None = None,
    loss_sink: str = "loss",
    yield_component: dict | None = None,
):
    """
    Convenience wrapper:
      - reads comp_abs from flow_in
      - partitions
      - applies yields -> loss_sink
      - builds MassFlow outputs
    """
    m_in = float(flow_in.mass_kg_per_h)
    meta_in = dict(getattr(flow_in, "meta", {}) or {})
    comp_abs_in = _get_comp_abs_from_flow(flow_in, m_in)

    streams = partition_comp_abs(comp_abs_in, partition or {}, default_stream=default_stream)
    streams = apply_yields(streams, yields or {}, loss_sink=loss_sink)
    streams = apply_component_yields(streams, yield_component or {}, loss_sink=loss_sink)
    outputs = build_outputs_from_comp_abs(streams, meta_in=meta_in)

    return outputs


