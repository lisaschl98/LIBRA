def get_step_cfg(step: str) -> dict:
    # You can make this strict during debugging:
    # if step not in EFF: raise KeyError(f"Step '{step}' not found in EFF.")
    override_key = _resolve_step_key(_STEP_CFG_OVERRIDES, step)
    if override_key is not None:
        return dict(_STEP_CFG_OVERRIDES[override_key])

    seen: set[str] = set()
    while step not in seen:
        seen.add(step)
        alias_key = _resolve_step_key(_STEP_CFG_ALIASES, step)
        if alias_key is None:
            break
        step = _STEP_CFG_ALIASES[alias_key]

    eff_key = _resolve_step_key(EFF, step)
    if eff_key is not None:
        return EFF.get(eff_key, {})
    return {}


def apply_step_cfg(step: str, flow_in, fallback_default_stream: str):
    """
    One-line helper for all steps:
      outputs = apply_step_cfg("Shredding", flow_in, "shredded")
    """
    cfg = get_step_cfg(step)

    default_stream = str(cfg.get("default_stream", fallback_default_stream))
    loss_sink = str(cfg.get("loss_sink", "loss"))
    partition = cfg.get("partition") or {}
    yields = dict(cfg.get("yield") or {})
    yield_component = dict(cfg.get("yield_component") or {})

    # Ensure pass-through if yield omitted for the forward/default stream
    yields.setdefault(default_stream, 1.0)

    return apply_partition_and_yield(
        step=step,
        flow_in=flow_in,
        default_stream=default_stream,
        partition=partition,
        yields=yields,
        loss_sink=loss_sink,
        yield_component=yield_component,
    )

from Massflow import MassFlow

def mf_get(outputs: dict, key: str) -> MassFlow:
    """Safe getter for MassFlow outputs (returns 0-flow if missing)."""
    return outputs.get(key, MassFlow(0.0, meta={"comp_abs": {}, "comp": {}}))

def sum_outputs_kg_h(outputs: dict) -> float:
    return float(sum(mf.mass_kg_per_h for mf in outputs.values()))

def stream_summary(step: str, outputs: dict, fallback_forward: str):
    """
    Standard summary for reporting (works for ANY step):
      - total out
      - forward stream
      - loss sink stream
      - side streams (all except forward+loss)
    """
    cfg = get_step_cfg(step)
    forward_key = str(cfg.get("default_stream", fallback_forward))
    loss_key = str(cfg.get("loss_sink", "loss"))

    m_forward = mf_get(outputs, forward_key).mass_kg_per_h
    m_loss = mf_get(outputs, loss_key).mass_kg_per_h
    m_out = sum_outputs_kg_h(outputs)

    side_keys = [k for k in outputs.keys() if k not in {forward_key, loss_key}]
    m_side = float(sum(mf_get(outputs, k).mass_kg_per_h for k in side_keys))

    return {
        "forward_key": forward_key,
        "loss_key": loss_key,
        "side_keys": side_keys,
        "m_out_kg_h": m_out,
        "m_forward_kg_h": m_forward,
        "m_loss_kg_h": m_loss,
        "m_side_kg_h": m_side,
    }
