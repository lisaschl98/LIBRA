def step_cfg_to_dataframe() -> pd.DataFrame:
    rows = []
    for step, cfg in EFF.items():
        default_stream = cfg.get("default_stream", "")
        loss_sink = cfg.get("loss_sink", "")
        partition = cfg.get("partition", {}) or {}
        yields = cfg.get("yield", {}) or {}
        yield_component = cfg.get("yield_component", {}) or {}

        for comp_key, y in yield_component.items():
            rows.append(
                {
                    "Step": step,
                    "Type": "yield_component",
                    "Key": comp_key,
                    "Value": float(y),
                    "default_stream": default_stream,
                    "loss_sink": loss_sink,
                }
            )

        # yields
        for stream, y in yields.items():
            rows.append(
                {
                    "Step": step,
                    "Type": "yield",
                    "Key": stream,
                    "Value": float(y),
                    "default_stream": default_stream,
                    "loss_sink": loss_sink,
                }
            )

        # partition
        for comp_key, dests in partition.items():
            for stream, frac in (dests or {}).items():
                rows.append(
                    {
                        "Step": step,
                        "Type": "partition",
                        "Key": f"{comp_key} -> {stream}",
                        "Value": float(frac),
                        "default_stream": default_stream,
                        "loss_sink": loss_sink,
                    }
                )

        # header row even if empty
        if not partition and not yields and not yield_component:
            rows.append(
                {
                    "Step": step,
                    "Type": "meta",
                    "Key": "-",
                    "Value": "",
                    "default_stream": default_stream,
                    "loss_sink": loss_sink,
                }
            )

    return pd.DataFrame(rows)


def save_recycling_efficiencies_to_excel(writer):
    df = step_cfg_to_dataframe()
    df.to_excel(writer, sheet_name="Recycling Efficiencies", index=False)