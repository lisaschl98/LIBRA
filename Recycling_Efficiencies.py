def _normalize_stream_key(key: str, drop_spaces: bool = False) -> str:
    """
    Normalize stream keys for tolerant matching.

    Handles common naming drift between code and EFF:
      - underscores vs spaces
      - mixed capitalization
      - comma spacing (", " vs ",")
      - accidental duplicate/nb spaces
    """
    s = str(key).replace("\u00A0", " ").strip().lower()
    s = s.replace("_", " ")
    s = " ".join(s.split())
    s = s.replace(" ,", ",").replace(", ", ",")
    if drop_spaces:
        s = s.replace(" ", "")
    return s


def _stream_key_variants(key: str) -> tuple[str, str]:
    return (
        _normalize_stream_key(key, drop_spaces=False),
        _normalize_stream_key(key, drop_spaces=True),
    )


def _normalize_step_key(key: str) -> str:
    """Normalize step names for tolerant matching across dash/spacing variants."""
    s = str(key).replace("\u00A0", " ").strip().lower()
    for dash in ("\u2010", "\u2011", "\u2012", "\u2013", "\u2014", "\u2212"):
        s = s.replace(dash, "-")
    s = s.replace(" - ", "-").replace("- ", "-").replace(" -", "-")
    return " ".join(s.split())


def _resolve_step_key(mapping: dict, step: str) -> str | None:
    if step in mapping:
        return step
    target = _normalize_step_key(step)
    for actual in mapping:
        if _normalize_step_key(actual) == target:
            return actual
    return None


class StreamOutputs(dict):
    """
    Dict-like container for step outputs with tolerant key lookup.

    Exact keys are preserved as generated by EFF/default_stream, but lookups
    can resolve common spelling variants (underscore/space/comma/case).
    """

    def _resolve_actual_key(self, key: str) -> str | None:
        if super().__contains__(key):
            return key

        variants = _stream_key_variants(key)
        for actual in super().keys():
            if _stream_key_variants(actual)[0] in variants or _stream_key_variants(actual)[1] in variants:
                return actual
        return None

    def __getitem__(self, key):
        actual = self._resolve_actual_key(key)
        if actual is None:
            raise KeyError(key)
        return super().__getitem__(actual)

    def get(self, key, default=None):
        actual = self._resolve_actual_key(key)
        if actual is None:
            return default
        return super().get(actual, default)

    def __contains__(self, key):
        return self._resolve_actual_key(key) is not None


def load_eff_from_excel(xlsx_path: str) -> dict[str, dict]:
    # Read all sheets (sheet_name=None -> dict of DataFrames)
    sheets = pd.read_excel(xlsx_path, sheet_name=None)
    
    # Merge all tables into one
    frames = []
    for name, df in sheets.items():
        if df is None or df.empty:
            continue
        frames.append(df)
    if not frames:
        raise ValueError(f"No data found in EFF Excel: {xlsx_path}")
    df_all = pd.concat(frames, ignore_index=True)
    
    # Normalize column names
    df_all.columns = [str(c).strip() for c in df_all.columns]
    
    required_cols = {"Step", "Type", "Key", "Value", "default_stream", "loss_sink"}
    missing = required_cols - set(df_all.columns)
    if missing:
        raise KeyError(f"Missing columns in EFF Excel {xlsx_path}: {missing}")
    
    # Clean strings
    df_all["Step"] = df_all["Step"].astype(str).str.strip()
    df_all["Type"] = df_all["Type"].astype(str).str.strip().str.lower()
    df_all["Key"] = df_all["Key"].astype(str).str.strip()
    # Value numerisch
    df_all["Value"] = pd.to_numeric(df_all["Value"], errors="coerce").fillna(0.0)
    df_all["default_stream"] = df_all["default_stream"].astype(str).str.strip()
    df_all["loss_sink"] = df_all["loss_sink"].astype(str).str.strip()
    
    eff: dict[str, dict] = {}
    
    # Build per-step configuration
    for step, sub in df_all.groupby("Step"):
        cfg: dict = {}
        
        # default_stream / loss_sink: use the first entry
        first = sub.iloc[0]
        cfg["default_stream"] = str(first["default_stream"])
        cfg["loss_sink"] = str(first["loss_sink"])
        
        # initialize partition & yield maps
        part: dict[str, dict] = {}
        yld: dict[str, float] = {}
        ycomp: dict[str, float] = {}
        
        for _, row in sub.iterrows():
            t = row["Type"]
            key = str(row["Key"])
            val = float(row["Value"])
            
            if t == "partition":
                # Key-Format: "<comp> -> <stream>"
                if "->" not in key:
                    raise ValueError(f"Invalid partition Key for step '{step}': '{key}'")
                comp_key, stream = key.split("->", 1)
                comp_key = comp_key.strip()
                stream = stream.strip()
                if comp_key not in part:
                    part[comp_key] = {}
                part[comp_key][stream] = val
            elif t == "yield":
                stream = key  # here key = stream name
                yld[stream] = val
            elif t == "yield_component":
                # Key is one component. (1-value) of that component goes to loss_sink.
                # Other components in the same stream are left unchanged.
                ycomp[key] = val
            else:
                # meta or empty -> ignore (only default_stream/loss_sink are relevant)
                continue
        
        cfg["partition"] = part
        cfg["yield"] = yld
        cfg["yield_component"] = ycomp
        
        eff[step] = cfg
    
    return eff

